export function getMenuItem(slug: string): MenuItem | undefined {
  return menuItems.find((item) => item.slug === slug);
}

export function getItemsByCategory(category: MenuItem["category"]): MenuItem[] {
  return menuItems.filter((item) => item.category === category);
}

export function getFeaturedDishes(limit = 4): MenuItem[] {
  return menuItems
    .filter((item) => item.featured && item.category !== "cocktail")
    .slice(0, limit);
}

export function getCocktails(): MenuItem[] {
  return getItemsByCategory("cocktail");
}

